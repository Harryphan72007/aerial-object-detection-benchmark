"""Measure per-model seconds/iteration on a real GPU and emit a runtime budget.

This is a GPU-only probe. It constructs each controlled-track adapter, runs a
fixed number of warm-up iterations, then times a fixed number of iterations with
the device synchronized around the timed window (see
``src.training.profiling.measure_iteration_seconds``). It records seconds per
iteration, peak GPU memory, the GPU name, and the torch/driver versions, writes
``throughput.json`` to the artifact root, and renders
``docs/reference/runtime_budget.md`` from the measurement plus the resolved
controlled protocol.

It cannot run without CUDA and cannot be validated on a CPU-only host. The
per-iteration number must be produced on the target hardware (Colab/L4/T4)
before any one-model-per-day claim is made; until then the runtime budget lists
``null`` hours, never a guess.

Usage (on a GPU host, with the model environments provisioned):

    python -m scripts.measure_throughput --repo-root . --drive-root <artifact_root> \
        --warmup 5 --iterations 20
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from src.config.benchmark_tracks import load_track_config, resolve_controlled_protocol
from src.training.profiling import (
    measure_iteration_seconds,
    memory_snapshot,
    render_runtime_budget,
)

# VisDrone2019-DET train image count (official). Used only to size the budget's
# iteration counts; the actual data is hashed per run elsewhere.
OFFICIAL_TRAIN_IMAGES = 6471


def _require_cuda() -> Any:
    try:
        import torch
    except ImportError as exc:  # pragma: no cover - GPU host only
        raise SystemExit("PyTorch is required to measure throughput") from exc
    if not torch.cuda.is_available():  # pragma: no cover - GPU host only
        raise SystemExit(
            "No CUDA device available. Throughput must be measured on the target "
            "GPU; this probe does not run on CPU."
        )
    return torch


def _environment(torch: Any) -> dict[str, Any]:  # pragma: no cover - GPU host only
    device = torch.cuda.current_device()
    return {
        "gpu_name": torch.cuda.get_device_name(device),
        "torch_version": torch.__version__,
        "cuda_version": torch.version.cuda,
        "driver": getattr(
            getattr(torch, "cuda", None), "get_device_properties", lambda _: None
        )(device).__str__(),
    }


def measure_model(
    model_id: str,
    repo_root: Path,
    *,
    image_size: int,
    warmup: int,
    iterations: int,
) -> dict[str, Any]:  # pragma: no cover - GPU host only
    """Construct the adapter and time one training-representative step.

    Requires the model's isolated environment to be importable. The step runs a
    forward pass on a two-image batch and, when the adapter exposes a training
    entry point, a backward pass; the measurement mode is recorded so the budget
    never conflates inference-only timing with training timing.
    """
    torch = _require_cuda()
    from src.models.registry import create_adapter, load_model_config

    config = load_model_config(model_id, repo_root)
    adapter = create_adapter(model_id)
    model = adapter.load_model("", config)

    batch = torch.randn(2, 3, image_size, image_size, device="cuda")
    forward_train = getattr(adapter, "forward_train", None) or getattr(
        model, "forward_train", None
    )
    mode = "train_forward_backward" if callable(forward_train) else "inference_forward"

    def step(_index: int) -> None:
        if mode == "train_forward_backward":
            loss = forward_train(batch)
            loss = loss["loss"] if isinstance(loss, dict) else loss
            loss.backward()
            model.zero_grad(set_to_none=True)
        else:
            with torch.no_grad():
                model(batch)

    torch.cuda.reset_peak_memory_stats()
    timing = measure_iteration_seconds(
        step,
        warmup=warmup,
        iterations=iterations,
        synchronize=torch.cuda.synchronize,
    )
    return {
        "model_id": model_id,
        "measurement_mode": mode,
        "image_size": image_size,
        **timing,
        "memory": memory_snapshot(),
        **_environment(torch),
    }


def _write_budget_doc(budget: dict[str, Any], repo_root: Path, environment: str) -> Path:
    doc = repo_root / "docs" / "reference" / "runtime_budget.md"
    iters = budget["iterations"]
    lines = [
        "# Runtime budget (generated)",
        "",
        f"Generated by `scripts/measure_throughput.py` on {environment}.",
        "",
        "| Model | s/iter | HPO h | Headline total h | Full-matrix total h |",
        "|---|---:|---:|---:|---:|",
    ]
    for model_id, record in budget["models"].items():
        t = record.get("seconds_per_iteration")
        if t is None:
            lines.append(f"| `{model_id}` | null | null | null | null |")
            continue
        lines.append(
            f"| `{model_id}` | {t:.3f} | {record['hpo_hours']} | "
            f"{record['headline_total_hours']} | {record['full_matrix_total_hours']} |"
        )
    lines += [
        "",
        f"Iteration counts (from config): HPO {iters['hpo_iterations']}, "
        f"headline final {iters['headline_final_iterations']}, "
        f"full-matrix final {iters['full_matrix_final_iterations']}.",
    ]
    doc.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return doc


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", default=".")
    parser.add_argument("--drive-root", required=True)
    parser.add_argument("--warmup", type=int, default=5)
    parser.add_argument("--iterations", type=int, default=20)
    args = parser.parse_args(argv)

    repo_root = Path(args.repo_root).resolve()
    track = load_track_config(repo_root, "controlled")
    protocol = resolve_controlled_protocol(repo_root, track["model_ids"][0])
    image_size = int(protocol["image_size"])

    measurements: dict[str, Any] = {}
    for model_id in track["model_ids"]:  # pragma: no cover - GPU host only
        measurements[model_id] = measure_model(
            model_id,
            repo_root,
            image_size=image_size,
            warmup=args.warmup,
            iterations=args.iterations,
        )

    out_dir = Path(args.drive_root).resolve() / "profiling"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "throughput.json").write_text(
        json.dumps(measurements, indent=2), encoding="utf-8"
    )

    budget = render_runtime_budget(
        measurements, protocol, official_train_images=OFFICIAL_TRAIN_IMAGES
    )
    environment = (
        next(iter(measurements.values())).get("gpu_name", "unknown GPU")
        if measurements
        else "unknown GPU"
    )
    _write_budget_doc(budget, repo_root, environment)
    print(json.dumps(budget, indent=2))
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
